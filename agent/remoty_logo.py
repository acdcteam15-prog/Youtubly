"""
The Remoty logo: a white "R" on a red rounded square.
One geometry (108 x 108 grid) feeds the Windows icon, the tray icon and the Android vector drawables
(Android files are generated by make_android_logo.py from the same shapes).
"""
import math

from PIL import Image, ImageDraw

RED_LIGHT = (255, 82, 82)    # #FF5252
RED_DARK = (183, 28, 28)     # #B71C1C
CENTER = (57.5, 54.0)        # visual center of the R in the 108 grid


def _arc(cx, cy, r, a0, a1, n=28):
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def r_shapes():
    """The letter R as separate polygons in a 108 x 108 grid (y points down)."""
    stem = [(36, 30), (48, 30), (48, 78), (36, 78)]
    cx, cy, ro, ri = 54.0, 45.5, 15.5, 5.0
    bowl = ([(48, 30), (cx, 30)] + _arc(cx, cy, ro, -90, 90) + [(cx, 61), (48, 61), (48, 50.5), (cx, 50.5)]
            + _arc(cx, cy, ri, 90, -90) + [(cx, 40.5), (48, 40.5)])
    leg = [(52, 60), (64, 60), (79, 78), (65, 78)]
    return [stem, bowl, leg]


def shapes_for(size: float, k: float):
    """The R centered in a size x size square, scaled by k (1.0 = as drawn in the 108 grid)."""
    f = k * size / 108.0
    return [[((x - CENTER[0]) * f + size / 2.0, (y - CENTER[1]) * f + size / 2.0) for x, y in poly] for poly in r_shapes()]


def render(px: int = 256, k: float = 1.35) -> "Image.Image":
    """RGBA logo image, px x px."""
    S = 512
    g = 64
    grad = Image.new("RGB", (g, g))
    pix = grad.load()
    for y in range(g):
        for x in range(g):
            t = (x + y) / (2.0 * (g - 1))
            pix[x, y] = tuple(int(RED_LIGHT[i] + (RED_DARK[i] - RED_LIGHT[i]) * t) for i in range(3))
    grad = grad.resize((S, S), Image.BICUBIC)
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.19), fill=255)
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    img.paste(grad, (0, 0), mask)
    d = ImageDraw.Draw(img)
    for poly in shapes_for(S, k):
        d.polygon(poly, fill=(255, 255, 255, 255))
    return img.resize((px, px), Image.LANCZOS)
