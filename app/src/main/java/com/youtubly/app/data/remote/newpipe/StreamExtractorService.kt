package com.youtubly.app.data.remote.newpipe

import com.youtubly.app.domain.model.AudioStreamOption
import com.youtubly.app.domain.model.CaptionTrack
import com.youtubly.app.domain.model.Chapter
import com.youtubly.app.domain.model.PreviewFrameSet
import com.youtubly.app.domain.model.StreamInfoResult
import com.youtubly.app.domain.model.Video
import com.youtubly.app.domain.model.VideoStreamOption
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.StreamingService
import org.schabi.newpipe.extractor.stream.AudioTrackType
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.stream.StreamType
import javax.inject.Inject

class StreamExtractorService @Inject constructor(
    private val streamingService: StreamingService
) {
    fun extractStreamInfo(videoUrl: String): StreamInfoResult {
        val info = StreamInfo.getInfo(streamingService, videoUrl)

        val video = Video(
            id = info.id,
            url = info.url,
            title = info.name,
            uploaderName = info.uploaderName ?: "",
            uploaderUrl = info.uploaderUrl,
            thumbnailUrl = info.thumbnails.maxByOrNull { it.height }?.url,
            duration = info.duration,
            viewCount = info.viewCount,
            uploadDate = info.textualUploadDate,
            isLive = info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM
        )

        val videoStreams = (info.videoStreams + info.videoOnlyStreams).map {
            VideoStreamOption(
                url = it.content,
                resolution = it.getResolution(),
                format = it.format?.name ?: "unknown",
                isVideoOnly = it.isVideoOnly(),
                codec = it.codec
            )
        }

        val audioStreams = info.audioStreams.map {
            AudioStreamOption(
                url = it.content,
                averageBitrate = it.averageBitrate,
                format = it.format?.name ?: "unknown",
                // Videos with auto-dubs list one track per language. ORIGINAL = the uploader's own
                // audio; null = YouTube didn't label it (single-track videos) → treat as original.
                isOriginal = it.audioTrackType == null || it.audioTrackType == AudioTrackType.ORIGINAL,
                languageTag = it.audioLocale?.toLanguageTag()
            )
        }

        return StreamInfoResult(
            video = video,
            description = info.description?.content,
            hlsUrl = info.hlsUrl?.takeIf { it.isNotBlank() },
            dashUrl = info.dashMpdUrl?.takeIf { it.isNotBlank() },
            videoStreams = videoStreams,
            audioStreams = audioStreams,
            relatedVideos = info.relatedItems.filterIsInstance<StreamInfoItem>().toVideosWithoutShorts(),
            likeCount = info.likeCount.takeIf { it >= 0 },
            captions = info.subtitles
                .filter { it.format == MediaFormat.VTT }
                .map {
                    CaptionTrack(
                        url = it.content,
                        languageTag = it.languageTag,
                        label = it.displayLanguageName + if (it.isAutoGenerated) " (auto)" else "",
                        autoGenerated = it.isAutoGenerated
                    )
                }
                .distinctBy { it.label }
                .sortedWith(compareBy({ it.autoGenerated }, { it.label })),
            chapters = info.streamSegments.map { Chapter(it.title, it.startTimeSeconds, it.previewUrl?.takeIf { u -> u.isNotBlank() }) },
            previewFrames = runCatching {
                PreviewFrameSet.best(
                    info.previewFrames.orEmpty().map {
                        PreviewFrameSet(
                            urls = it.urls,
                            frameWidth = it.frameWidth,
                            frameHeight = it.frameHeight,
                            totalCount = it.totalCount,
                            durationPerFrameMs = it.durationPerFrame,
                            columns = it.framesPerPageX,
                            rows = it.framesPerPageY
                        )
                    }
                )
            }.getOrNull()
        )
    }
}
