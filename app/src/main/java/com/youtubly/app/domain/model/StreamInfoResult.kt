package com.youtubly.app.domain.model

/**
 * @param isOriginal false for YouTube's extra audio tracks (auto-dubbed / translated languages,
 *  descriptive audio). Defaults to true so single-track videos and tests behave as before.
 * @param languageTag BCP-47 tag of this track's language when YouTube reports one.
 */
data class AudioStreamOption(
    val url: String,
    val averageBitrate: Int,
    val format: String,
    val isOriginal: Boolean = true,
    val languageTag: String? = null
)

/** Only the video's own audio: drops dubbed/translated/descriptive tracks when an original
 *  one exists (if YouTube marks none as original, keeps everything rather than nothing). */
fun List<AudioStreamOption>.originalOnly(): List<AudioStreamOption> =
    filter { it.isOriginal }.ifEmpty { this }

data class VideoStreamOption(
    val url: String,
    val resolution: String,
    val format: String,
    val isVideoOnly: Boolean,
    /** e.g. "avc1.640028", "av01.0.08M.08", "vp9" — null when YouTube didn't say. */
    val codec: String? = null
) {
    /** "1080p60" → 1080 */
    val height: Int get() = resolution.takeWhile(Char::isDigit).toIntOrNull() ?: 0
}

data class CaptionTrack(
    val url: String,
    val languageTag: String,
    val label: String,
    val autoGenerated: Boolean
)

data class Chapter(val title: String, val startSeconds: Int, val thumbnailUrl: String? = null)

data class StreamInfoResult(
    val video: Video,
    val description: String?,
    val hlsUrl: String?,
    val dashUrl: String?,
    val videoStreams: List<VideoStreamOption>,
    val audioStreams: List<AudioStreamOption>,
    val relatedVideos: List<Video>,
    val likeCount: Long?,
    val captions: List<CaptionTrack> = emptyList(),
    val chapters: List<Chapter> = emptyList(),
    /** Seek-bar preview storyboard (best level), when YouTube provides one. */
    val previewFrames: PreviewFrameSet? = null
)
